-- One row per uploaded trade. All ~121 source columns are kept as-is (lower snake_case of
-- the original field name), plus a handful of columns the engine adds on store.
-- Partitioned by month of trade_date; MariaDB requires the partition column to be part of
-- every unique key, so the primary key is (id, trade_date) rather than id alone. trades_tags
-- references trade id without a DB-level foreign key for this reason (standard practice for
-- large partitioned fact tables).
-- Text columns are VARCHAR(100): with 121 columns, VARCHAR(255) in utf8mb4 exceeds MariaDB's
-- 65,535-byte row size limit.
